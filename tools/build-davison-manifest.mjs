const roman = n => {
  const values = [[40, "XL"], [10, "X"], [9, "IX"], [5, "V"], [4, "IV"], [1, "I"]];
  let value = "";
  for (const [amount, symbol] of values) while (n >= amount) (value += symbol), (n -= amount);
  return value;
};

const pageList = value => Array.isArray(value) ? value : [value];
const chapters = [];

function addChapter(number, title, printedPages, entries) {
  const chapterId = `davison-ch${String(number).padStart(2, "0")}`;
  chapters.push({
    id: chapterId,
    number,
    roman: roman(number),
    title,
    printedPages,
    entries: entries.map(([title, pages], index) => ({
      id: `${chapterId}-n${String(index + 1).padStart(3, "0")}`,
      order: index + 1,
      sourceNumber: number === 1 ? roman(index + 1) : String(index + 1),
      kind: number === 1 ? "treadling" : "threading",
      title,
      printedPages: pageList(pages),
    })),
  });
}

